-- Unusual gateway requests (rate limited, rejected, missing, failed, slow), kept for tracing.
CREATE TABLE gateway_event (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at timestamp(6) with time zone NOT NULL,
    kind character varying(32) NOT NULL,
    ip character varying(64) NOT NULL,
    host character varying(255),
    method character varying(16),
    path character varying(512),
    status integer NOT NULL,
    request_time_ms integer NOT NULL DEFAULT 0,
    upstream character varying(128),
    request_id character varying(64),
    cf_ray character varying(64),
    user_agent character varying(255),
    suppressed integer NOT NULL DEFAULT 0
);

CREATE INDEX idx_gateway_event_occurred_at ON gateway_event (occurred_at DESC);
CREATE INDEX idx_gateway_event_ip ON gateway_event (ip, occurred_at DESC);
CREATE INDEX idx_gateway_event_kind ON gateway_event (kind, occurred_at DESC);
CREATE INDEX idx_gateway_event_request_id ON gateway_event (request_id);

-- One row each time a service changes between UP and DOWN.
CREATE TABLE service_health_event (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at timestamp(6) with time zone NOT NULL,
    service character varying(64) NOT NULL,
    state character varying(8) NOT NULL,
    detail character varying(255)
);

CREATE INDEX idx_service_health_event_service ON service_health_event (service, occurred_at DESC);
CREATE INDEX idx_service_health_event_occurred_at ON service_health_event (occurred_at DESC);
