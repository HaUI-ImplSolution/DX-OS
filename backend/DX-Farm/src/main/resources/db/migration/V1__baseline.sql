CREATE TABLE crop_seasons (
    id bigint NOT NULL,
    expected_harvest_date date,
    harvested_at timestamp(6) with time zone,
    rice_variety character varying(255) NOT NULL,
    start_date date NOT NULL,
    status character varying(255) NOT NULL,
    version bigint DEFAULT 0 NOT NULL,
    parcel_id bigint NOT NULL,
    CONSTRAINT crop_seasons_status_check CHECK (((status)::text = ANY ((ARRAY['ACTIVE'::character varying, 'HARVESTED'::character varying])::text[])))
);

