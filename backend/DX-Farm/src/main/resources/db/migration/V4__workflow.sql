-- Shared workflow: one case per approvable entity, an append-only event log per case.
CREATE TABLE workflow_case (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_type character varying(64) NOT NULL,
    entity_type character varying(64) NOT NULL,
    entity_id bigint NOT NULL,
    status character varying(32) NOT NULL,
    created_by character varying(255),
    created_at timestamp(6) with time zone NOT NULL,
    assigned_to character varying(255),
    assigned_to_name character varying(255),
    updated_at timestamp(6) with time zone NOT NULL,
    version bigint DEFAULT 0 NOT NULL,
    CONSTRAINT workflow_case_status_check
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED')),
    CONSTRAINT uq_workflow_case_entity UNIQUE (case_type, entity_type, entity_id)
);

CREATE INDEX idx_workflow_case_type_status ON workflow_case (case_type, status);
CREATE INDEX idx_workflow_case_assigned_to ON workflow_case (assigned_to);

CREATE TABLE workflow_event (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workflow_case_id bigint NOT NULL REFERENCES workflow_case (id),
    action character varying(32) NOT NULL,
    from_status character varying(32),
    to_status character varying(32) NOT NULL,
    actor_user_id character varying(255),
    actor_display_name character varying(255),
    reason character varying(255),
    occurred_at timestamp(6) with time zone NOT NULL,
    metadata jsonb
);

CREATE INDEX idx_workflow_event_case ON workflow_event (workflow_case_id, occurred_at, id);

-- Events are history: they can be added but never changed or removed.
CREATE FUNCTION workflow_event_append_only() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'workflow_event is append-only';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER workflow_event_no_update_delete
BEFORE UPDATE OR DELETE ON workflow_event
FOR EACH ROW EXECUTE FUNCTION workflow_event_append_only();

-- Diagnoses that already exist get a case with the decisions they carry, so the pending list
-- matches the diagnoses that are really pending.
INSERT INTO workflow_case (case_type, entity_type, entity_id, status, created_by, created_at,
                           updated_at)
SELECT 'DIAGNOSIS_APPROVAL', 'DIAGNOSIS', d.id, d.approval_status, NULL, d.diagnosed_at,
       COALESCE(d.decided_at, d.diagnosed_at)
FROM diagnoses d;

INSERT INTO workflow_event (workflow_case_id, action, from_status, to_status, occurred_at)
SELECT c.id, 'SUBMITTED', NULL, 'PENDING', c.created_at
FROM workflow_case c;

INSERT INTO workflow_event (workflow_case_id, action, from_status, to_status, actor_user_id,
                            actor_display_name, reason, occurred_at)
SELECT c.id, d.approval_status, 'PENDING', d.approval_status, d.decided_by_user_id, d.decided_by,
       d.rejection_reason, COALESCE(d.decided_at, c.updated_at)
FROM workflow_case c
JOIN diagnoses d ON d.id = c.entity_id
WHERE c.entity_type = 'DIAGNOSIS' AND d.approval_status <> 'PENDING';
