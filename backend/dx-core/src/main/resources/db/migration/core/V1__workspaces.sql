-- Workspaces: the unit an app attaches its data to, such as a team or a class.
CREATE TABLE workspaces (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code character varying(64) NOT NULL,
    type character varying(32) NOT NULL,
    name character varying(255) NOT NULL,
    phone character varying(255),
    address character varying(255),
    attributes jsonb,
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT uq_workspaces_code UNIQUE (code)
);

-- Accounts that belong to a workspace, linked through the token "sub" claim.
CREATE TABLE workspace_members (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id bigint NOT NULL REFERENCES workspaces (id),
    user_id character varying(255) NOT NULL,
    role character varying(32) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT uq_workspace_members UNIQUE (workspace_id, user_id),
    CONSTRAINT workspace_members_role_check CHECK (role IN ('OWNER', 'MEMBER'))
);

-- At most one owner per workspace.
CREATE UNIQUE INDEX uq_workspace_members_owner ON workspace_members (workspace_id)
    WHERE role = 'OWNER';
CREATE INDEX idx_workspace_members_user_id ON workspace_members (user_id);

-- Next code number per workspace type.
CREATE TABLE workspace_code_counter (
    type character varying(32) PRIMARY KEY,
    last_number bigint NOT NULL
);
