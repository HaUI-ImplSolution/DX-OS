-- Chat messages the webhook could not deliver (network error, 5xx, 429), kept to be sent again.
-- A row is deleted once sent; FAILED rows (retries used up) stay for a few days for inspection.
CREATE TABLE chat_outbox (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_key character varying(64) NOT NULL,
    payload jsonb NOT NULL,
    status character varying(16) NOT NULL DEFAULT 'PENDING',
    attempts integer NOT NULL DEFAULT 1,
    last_error character varying(200),
    next_attempt_at timestamp(6) with time zone NOT NULL,
    created_at timestamp(6) with time zone NOT NULL DEFAULT now(),
    CONSTRAINT ck_chat_outbox_status CHECK (status IN ('PENDING', 'FAILED'))
);

CREATE INDEX idx_chat_outbox_due ON chat_outbox (next_attempt_at) WHERE status = 'PENDING';
