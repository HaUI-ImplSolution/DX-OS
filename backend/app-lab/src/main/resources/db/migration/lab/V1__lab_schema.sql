-- Lab schema: catalogues, support tickets, device maintenance and loans, room bookings.
-- Workflow state lives in the core workflow tables; the status columns here mirror the case
-- status so lists and statistics need no join into the core.

-- Lets one constraint combine equality on room_id with overlap on the booked time range.
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE rooms (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code character varying(32) NOT NULL,
    building character varying(64) NOT NULL,
    name character varying(255) NOT NULL,
    room_type character varying(32) NOT NULL,
    capacity integer NOT NULL,
    status character varying(32) NOT NULL DEFAULT 'AVAILABLE',
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    version bigint NOT NULL DEFAULT 0,
    CONSTRAINT uq_rooms_code UNIQUE (code),
    CONSTRAINT rooms_room_type_check CHECK (room_type IN ('COMPUTER_LAB', 'CLASSROOM', 'MEETING_ROOM')),
    CONSTRAINT rooms_status_check CHECK (status IN ('AVAILABLE', 'MAINTENANCE')),
    CONSTRAINT rooms_capacity_check CHECK (capacity > 0)
);

CREATE TABLE devices (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_code character varying(64) NOT NULL,
    device_type character varying(64) NOT NULL,
    model character varying(255),
    serial_number character varying(128),
    room_id bigint REFERENCES rooms (id),
    status character varying(32) NOT NULL DEFAULT 'AVAILABLE',
    purchased_on date,
    warranty_until date,
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    version bigint NOT NULL DEFAULT 0,
    CONSTRAINT uq_devices_asset_code UNIQUE (asset_code),
    CONSTRAINT devices_status_check CHECK (status IN ('AVAILABLE', 'ON_LOAN', 'UNDER_REPAIR', 'RETIRED'))
);
CREATE INDEX idx_devices_room_id ON devices (room_id);
CREATE INDEX idx_devices_status ON devices (status);

CREATE TABLE ticket_categories (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code character varying(48) NOT NULL,
    name character varying(255) NOT NULL,
    default_priority character varying(16) NOT NULL,
    keywords character varying(1000),
    active boolean NOT NULL DEFAULT true,
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    version bigint NOT NULL DEFAULT 0,
    CONSTRAINT uq_ticket_categories_code UNIQUE (code),
    CONSTRAINT ticket_categories_priority_check
        CHECK (default_priority IN ('URGENT', 'HIGH', 'NORMAL', 'LOW'))
);

-- One row per priority: how long the first response and the resolution may take.
CREATE TABLE sla_policies (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    priority character varying(16) NOT NULL,
    response_minutes integer NOT NULL,
    resolution_minutes integer NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    version bigint NOT NULL DEFAULT 0,
    CONSTRAINT uq_sla_policies_priority UNIQUE (priority),
    CONSTRAINT sla_policies_priority_check
        CHECK (priority IN ('URGENT', 'HIGH', 'NORMAL', 'LOW')),
    CONSTRAINT sla_policies_minutes_check
        CHECK (response_minutes > 0 AND resolution_minutes >= response_minutes)
);

-- Next ticket number per year.
CREATE TABLE ticket_code_counter (
    ticket_year integer PRIMARY KEY,
    last_number integer NOT NULL
);

CREATE TABLE tickets (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code character varying(32) NOT NULL,
    title character varying(255) NOT NULL,
    description character varying(4000) NOT NULL,
    category_id bigint NOT NULL REFERENCES ticket_categories (id),
    priority character varying(16) NOT NULL,
    room_id bigint REFERENCES rooms (id),
    device_id bigint REFERENCES devices (id),
    workspace_id bigint,
    requester_id character varying(255) NOT NULL,
    requester_name character varying(255) NOT NULL,
    status character varying(32) NOT NULL,
    assignee_id character varying(255),
    assignee_name character varying(255),
    workflow_case_id bigint,
    response_due_at timestamp(6) with time zone NOT NULL,
    resolution_due_at timestamp(6) with time zone NOT NULL,
    first_responded_at timestamp(6) with time zone,
    resolved_at timestamp(6) with time zone,
    closed_at timestamp(6) with time zone,
    resolution_note character varying(2000),
    root_cause character varying(1000),
    reopen_count integer NOT NULL DEFAULT 0,
    rating integer,
    rating_comment character varying(1000),
    sla_warned_at timestamp(6) with time zone,
    overdue boolean NOT NULL DEFAULT false,
    overdue_at timestamp(6) with time zone,
    client_request_id uuid,
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    version bigint NOT NULL DEFAULT 0,
    CONSTRAINT uq_tickets_code UNIQUE (code),
    CONSTRAINT uq_tickets_client_request_id UNIQUE (client_request_id),
    CONSTRAINT tickets_priority_check CHECK (priority IN ('URGENT', 'HIGH', 'NORMAL', 'LOW')),
    CONSTRAINT tickets_rating_check CHECK (rating IS NULL OR rating BETWEEN 1 AND 5)
);
CREATE INDEX idx_tickets_status ON tickets (status);
CREATE INDEX idx_tickets_requester_id ON tickets (requester_id);
CREATE INDEX idx_tickets_assignee_id ON tickets (assignee_id);
CREATE INDEX idx_tickets_created_at ON tickets (created_at);
-- The SLA job only looks at tickets still open and not yet marked overdue.
CREATE INDEX idx_tickets_sla_open ON tickets (resolution_due_at)
    WHERE overdue = false AND status IN ('NEW', 'ASSIGNED', 'IN_PROGRESS', 'WAITING_USER');

CREATE TABLE ticket_comments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id bigint NOT NULL REFERENCES tickets (id),
    author_id character varying(255) NOT NULL,
    author_name character varying(255) NOT NULL,
    staff boolean NOT NULL,
    internal boolean NOT NULL DEFAULT false,
    body character varying(4000) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL
);
CREATE INDEX idx_ticket_comments_ticket_id ON ticket_comments (ticket_id);

CREATE TABLE ticket_attachments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id bigint NOT NULL REFERENCES tickets (id),
    object_key character varying(255) NOT NULL,
    filename character varying(255) NOT NULL,
    content_type character varying(100) NOT NULL,
    size_bytes bigint NOT NULL,
    uploaded_by character varying(255) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL
);
CREATE INDEX idx_ticket_attachments_ticket_id ON ticket_attachments (ticket_id);

CREATE TABLE device_maintenance (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id bigint NOT NULL REFERENCES devices (id),
    kind character varying(16) NOT NULL,
    note character varying(2000) NOT NULL,
    ticket_id bigint REFERENCES tickets (id),
    performed_by_id character varying(255) NOT NULL,
    performed_by_name character varying(255) NOT NULL,
    started_at timestamp(6) with time zone NOT NULL,
    completed_at timestamp(6) with time zone,
    completion_note character varying(2000),
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT device_maintenance_kind_check CHECK (kind IN ('REPAIR', 'INSPECTION', 'REPLACEMENT'))
);
CREATE INDEX idx_device_maintenance_device_id ON device_maintenance (device_id);
-- A device has at most one maintenance entry in progress.
CREATE UNIQUE INDEX uq_device_maintenance_open ON device_maintenance (device_id)
    WHERE completed_at IS NULL;

CREATE TABLE device_loans (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id bigint NOT NULL REFERENCES devices (id),
    borrower_id character varying(255) NOT NULL,
    borrower_name character varying(255) NOT NULL,
    borrower_role character varying(32) NOT NULL,
    workspace_id bigint,
    purpose character varying(500) NOT NULL,
    due_date date NOT NULL,
    status character varying(32) NOT NULL,
    approved_by_id character varying(255),
    approved_by_name character varying(255),
    approved_at timestamp(6) with time zone,
    rejection_reason character varying(1000),
    returned_at timestamp(6) with time zone,
    return_condition character varying(16),
    return_note character varying(1000),
    workflow_case_id bigint,
    client_request_id uuid,
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    version bigint NOT NULL DEFAULT 0,
    CONSTRAINT uq_device_loans_client_request_id UNIQUE (client_request_id),
    CONSTRAINT device_loans_status_check
        CHECK (status IN ('PENDING', 'APPROVED', 'RETURNED', 'REJECTED', 'CANCELLED')),
    CONSTRAINT device_loans_condition_check
        CHECK (return_condition IS NULL OR return_condition IN ('GOOD', 'DAMAGED'))
);
CREATE INDEX idx_device_loans_device_id ON device_loans (device_id);
CREATE INDEX idx_device_loans_borrower_id ON device_loans (borrower_id);
CREATE INDEX idx_device_loans_status_due ON device_loans (status, due_date);

CREATE TABLE room_bookings (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id bigint NOT NULL REFERENCES rooms (id),
    requester_id character varying(255) NOT NULL,
    requester_name character varying(255) NOT NULL,
    requester_role character varying(32) NOT NULL,
    workspace_id bigint,
    title character varying(255) NOT NULL,
    attendees integer NOT NULL,
    starts_at timestamp(6) with time zone NOT NULL,
    ends_at timestamp(6) with time zone NOT NULL,
    -- A booking holds its slot from the request until it is rejected or cancelled.
    active boolean NOT NULL DEFAULT true,
    status character varying(32) NOT NULL,
    rejection_reason character varying(1000),
    workflow_case_id bigint,
    client_request_id uuid,
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    version bigint NOT NULL DEFAULT 0,
    CONSTRAINT uq_room_bookings_client_request_id UNIQUE (client_request_id),
    CONSTRAINT room_bookings_status_check
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED')),
    CONSTRAINT room_bookings_range_check CHECK (ends_at > starts_at),
    CONSTRAINT room_bookings_attendees_check CHECK (attendees > 0),
    -- Two live bookings of one room never share a moment, even when requested at the same time.
    CONSTRAINT room_bookings_no_overlap
        EXCLUDE USING gist (room_id WITH =, tstzrange(starts_at, ends_at) WITH &&)
        WHERE (active)
);
CREATE INDEX idx_room_bookings_requester_id ON room_bookings (requester_id);
CREATE INDEX idx_room_bookings_room_starts ON room_bookings (room_id, starts_at);
