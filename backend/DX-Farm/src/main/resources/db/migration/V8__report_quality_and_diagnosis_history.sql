-- Backend owns engineer labels; AI owns only its evidence corpus.
CREATE TABLE training_labels (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    disease_report_id bigint NOT NULL REFERENCES disease_reports(id),
    diagnosis_id bigint NOT NULL UNIQUE REFERENCES diagnoses(id),
    source_diagnosis_id bigint REFERENCES diagnoses(id),
    symptom_text text,
    disease_code varchar(255) NOT NULL,
    engineer_user_id varchar(255) NOT NULL,
    labeled_at timestamp(6) with time zone NOT NULL
);
CREATE INDEX idx_training_labels_report ON training_labels(disease_report_id);
