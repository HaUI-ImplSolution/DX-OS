-- Harvest declaration, harvest date changes, farmer-reported spraying and the in-app inbox.

-- Crop seasons: what was really harvested, by whom, and why an early harvest was allowed.
ALTER TABLE crop_seasons ADD COLUMN actual_harvest_date date;
ALTER TABLE crop_seasons ADD COLUMN yield_kg numeric(12, 2);
ALTER TABLE crop_seasons ADD COLUMN harvested_area_hectares numeric(10, 2);
ALTER TABLE crop_seasons ADD COLUMN harvested_by_user_id character varying(255);
ALTER TABLE crop_seasons ADD COLUMN harvested_by_name character varying(255);
ALTER TABLE crop_seasons ADD COLUMN early_reason character varying(255);
ALTER TABLE crop_seasons ADD COLUMN harvest_on_behalf_reason character varying(255);

-- Every change of the expected harvest date, oldest first.
CREATE TABLE harvest_reschedules (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crop_season_id bigint NOT NULL REFERENCES crop_seasons (id),
    previous_date date NOT NULL,
    new_date date NOT NULL,
    reason character varying(255) NOT NULL,
    rescheduled_by_user_id character varying(255),
    rescheduled_by_name character varying(255),
    rescheduled_at timestamp(6) with time zone NOT NULL
);

CREATE INDEX idx_harvest_reschedules_season ON harvest_reschedules (crop_season_id, id);

-- Treatment applications: a farmer reports the spraying, an engineer confirms it. Applications
-- recorded before this change were entered by staff, so they count as confirmed.
ALTER TABLE treatment_applications ADD COLUMN confirmation_status character varying(32) NOT NULL DEFAULT 'CONFIRMED';
ALTER TABLE treatment_applications ALTER COLUMN confirmation_status DROP DEFAULT;
ALTER TABLE treatment_applications ADD COLUMN reported_by_user_id character varying(255);
ALTER TABLE treatment_applications ADD COLUMN confirmed_by_user_id character varying(255);
ALTER TABLE treatment_applications ADD COLUMN confirmed_at timestamp(6) with time zone;
ALTER TABLE treatment_applications ADD COLUMN rejection_reason character varying(255);
ALTER TABLE treatment_applications ADD CONSTRAINT treatment_applications_confirmation_status_check
    CHECK (confirmation_status IN ('PENDING_CONFIRMATION', 'CONFIRMED', 'REJECTED'));

-- In-app inbox: one row per message, read state kept on the server so every device agrees.
CREATE TABLE notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_user_id character varying(255) NOT NULL,
    type character varying(48) NOT NULL,
    title character varying(255) NOT NULL,
    body character varying(1000) NOT NULL,
    related_entity_type character varying(48),
    related_entity_ref character varying(64),
    -- Set on reminders so one cannot be created twice for the same day.
    dedup_key character varying(128),
    read_at timestamp(6) with time zone,
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT uq_notifications_dedup_key UNIQUE (dedup_key)
);

CREATE INDEX idx_notifications_recipient ON notifications (recipient_user_id, created_at DESC, id DESC);
CREATE INDEX idx_notifications_recipient_unread ON notifications (recipient_user_id) WHERE read_at IS NULL;
