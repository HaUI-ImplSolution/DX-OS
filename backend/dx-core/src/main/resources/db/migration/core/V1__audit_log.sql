CREATE TABLE audit_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at timestamp(6) with time zone NOT NULL,
    actor_user_id character varying(255),
    actor_name character varying(255),
    actor_roles character varying(255),
    client_id character varying(255),
    action character varying(64) NOT NULL,
    target_type character varying(64),
    target_id character varying(255),
    outcome character varying(16) NOT NULL,
    ip character varying(64),
    request_id character varying(64),
    http_method character varying(16),
    path character varying(512),
    metadata jsonb
);

CREATE INDEX idx_audit_log_occurred_at ON audit_log (occurred_at DESC, id DESC);
CREATE INDEX idx_audit_log_actor ON audit_log (actor_user_id, occurred_at DESC);
CREATE INDEX idx_audit_log_action ON audit_log (action, occurred_at DESC);
CREATE INDEX idx_audit_log_denied_ip ON audit_log (outcome, occurred_at DESC, ip);

-- The log is history: rows can be added but never changed or removed.
CREATE FUNCTION audit_log_append_only() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'audit_log is append-only';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER audit_log_no_update_delete
BEFORE UPDATE OR DELETE ON audit_log
FOR EACH ROW EXECUTE FUNCTION audit_log_append_only();
