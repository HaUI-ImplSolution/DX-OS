-- Farm households: parcels belong to a household, a household is linked to a Keycloak account
-- through the token "sub" claim.
CREATE SEQUENCE household_code_seq START WITH 1;

CREATE TABLE households (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code character varying(255) NOT NULL,
    full_name character varying(255) NOT NULL,
    phone character varying(255),
    address character varying(255),
    keycloak_user_id character varying(255),
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT uq_households_code UNIQUE (code),
    CONSTRAINT uq_households_keycloak_user_id UNIQUE (keycloak_user_id)
);

ALTER TABLE parcels ADD COLUMN household_id bigint REFERENCES households (id);

-- Legacy parcels only carry a free-text owner name. One household per distinct name (compared
-- case-insensitively, as the old access check did); households created here have no account
-- yet and are linked to one by an administrator.
INSERT INTO households (code, full_name, created_at, updated_at)
SELECT 'H' || lpad(nextval('household_code_seq')::text, 4, '0'), o.full_name, now(), now()
FROM (
    SELECT DISTINCT ON (lower(btrim(farmer_name))) btrim(farmer_name) AS full_name, id AS first_id
    FROM parcels
    ORDER BY lower(btrim(farmer_name)), id
) o
ORDER BY o.first_id;

UPDATE parcels p
SET household_id = h.id
FROM households h
WHERE lower(btrim(p.farmer_name)) = lower(h.full_name);

ALTER TABLE parcels ALTER COLUMN household_id SET NOT NULL;
CREATE INDEX idx_parcels_household_id ON parcels (household_id);
