-- Harvest declaration, harvest date changes and farmer-reported spraying.

-- Crop seasons: what was really harvested, by whom, and why an early harvest was allowed.
ALTER TABLE crop_seasons ADD COLUMN actual_harvest_date date;
ALTER TABLE crop_seasons ADD COLUMN yield_kg numeric(12, 2);
ALTER TABLE crop_seasons ADD COLUMN harvested_area_hectares numeric(10, 2);
ALTER TABLE crop_seasons ADD COLUMN harvested_by_user_id character varying(255);
ALTER TABLE crop_seasons ADD COLUMN harvested_by_name character varying(255);
ALTER TABLE crop_seasons ADD COLUMN early_reason character varying(255);
ALTER TABLE crop_seasons ADD COLUMN harvest_on_behalf_reason character varying(255);

-- Every change of the expected harvest date, oldest first.
CREATE TABLE harvest_reschedules (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crop_season_id bigint NOT NULL REFERENCES crop_seasons (id),
    previous_date date NOT NULL,
    new_date date NOT NULL,
    reason character varying(255) NOT NULL,
    rescheduled_by_user_id character varying(255),
    rescheduled_by_name character varying(255),
    rescheduled_at timestamp(6) with time zone NOT NULL
);

CREATE INDEX idx_harvest_reschedules_season ON harvest_reschedules (crop_season_id, id);

