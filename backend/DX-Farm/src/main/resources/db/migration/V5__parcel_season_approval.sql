-- Parcels and crop seasons go through approval, carry generated codes and a GPS fix.

-- Parcels: approval state, GPS accuracy, idempotency key. Existing parcels count as approved.
ALTER TABLE parcels ADD COLUMN approval_status character varying(32) NOT NULL DEFAULT 'APPROVED';
ALTER TABLE parcels ALTER COLUMN approval_status DROP DEFAULT;
ALTER TABLE parcels ADD COLUMN rejection_reason character varying(255);
ALTER TABLE parcels ADD COLUMN gps_accuracy_meters numeric(7, 2);
ALTER TABLE parcels ADD COLUMN location_missing boolean NOT NULL DEFAULT false;
ALTER TABLE parcels ADD COLUMN client_request_id uuid;
ALTER TABLE parcels ADD CONSTRAINT uq_parcels_client_request_id UNIQUE (client_request_id);
ALTER TABLE parcels ADD CONSTRAINT parcels_approval_status_check
    CHECK (approval_status IN ('PENDING', 'APPROVED', 'REJECTED'));

UPDATE parcels SET location_missing = true WHERE latitude IS NULL OR longitude IS NULL;

-- Next parcel number per household, so a generated code is never reused after a delete.
CREATE TABLE household_parcel_counter (
    household_id bigint PRIMARY KEY REFERENCES households (id),
    last_number integer NOT NULL
);

INSERT INTO household_parcel_counter (household_id, last_number)
SELECT household_id, COUNT(*) FROM parcels GROUP BY household_id;

-- Rice variety catalogue: growth duration drives the suggested harvest date.
CREATE TABLE rice_varieties (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code character varying(32) NOT NULL UNIQUE,
    name character varying(128) NOT NULL,
    growth_days_min integer NOT NULL,
    growth_days_max integer NOT NULL,
    source character varying(255) NOT NULL,
    review_status character varying(32) NOT NULL,
    active boolean NOT NULL DEFAULT true,
    CONSTRAINT rice_varieties_growth_days_check
        CHECK (growth_days_min > 0 AND growth_days_max >= growth_days_min),
    CONSTRAINT rice_varieties_review_status_check
        CHECK (review_status IN ('APPROVED', 'IN_REVIEW'))
);

