    CHECK (season_type IS NULL OR season_type IN ('DONG_XUAN', 'HE_THU', 'THU_DONG'));

UPDATE crop_seasons SET season_year = EXTRACT(YEAR FROM start_date);

-- A rejected season is a draft: it no longer holds the parcel's single ACTIVE slot or its
-- (year, season type) slot.
DROP INDEX uq_crop_seasons_one_active_per_parcel;
CREATE UNIQUE INDEX uq_crop_seasons_one_active_per_parcel
ON crop_seasons (parcel_id)
WHERE status = 'ACTIVE' AND deleted_at IS NULL AND approval_status <> 'REJECTED';

CREATE UNIQUE INDEX uq_crop_seasons_parcel_year_type
ON crop_seasons (parcel_id, season_year, season_type)
WHERE deleted_at IS NULL AND approval_status <> 'REJECTED' AND season_type IS NOT NULL;

-- Change requests for an approved parcel. The decision lives in the workflow case.
CREATE TABLE parcel_edit_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parcel_id bigint NOT NULL REFERENCES parcels (id),
    area_hectares numeric(10, 2) NOT NULL,
    location character varying(255),
    latitude numeric(9, 6) NOT NULL,
    longitude numeric(9, 6) NOT NULL,
    gps_accuracy_meters numeric(7, 2),
    reason character varying(255),
    requested_by_user_id character varying(255),
    created_at timestamp(6) with time zone NOT NULL
);

CREATE INDEX idx_parcel_edit_requests_parcel ON parcel_edit_requests (parcel_id);
