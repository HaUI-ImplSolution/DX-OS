-- Hourly weather readings per rounded parcel position, collected by WeatherObservationScheduler
-- from live Open-Meteo data only. day_* hold the forecast of the reading's own day.
CREATE TABLE weather_observations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    latitude numeric(5, 2) NOT NULL,
    longitude numeric(5, 2) NOT NULL,
    observed_at timestamp(6) with time zone NOT NULL,
    temperature_c double precision NOT NULL,
    humidity_percent double precision NOT NULL,
    wind_speed_kmh double precision NOT NULL,
    weather_code integer NOT NULL,
    day_temp_max_c double precision NOT NULL,
    day_temp_min_c double precision NOT NULL,
    day_precipitation_mm double precision NOT NULL,
    CONSTRAINT uq_weather_observations_cell_hour UNIQUE (latitude, longitude, observed_at)
);

-- One row per position and local day for BI: the day's range, rainfall and mean humidity and wind.
CREATE VIEW vw_weather_daily AS
SELECT latitude, longitude,
       (observed_at AT TIME ZONE 'Asia/Ho_Chi_Minh')::date AS observed_date,
       MAX(day_temp_max_c) AS temp_max_c,
       MIN(day_temp_min_c) AS temp_min_c,
       MAX(day_precipitation_mm) AS precipitation_mm,
       AVG(humidity_percent) AS avg_humidity_percent,
       AVG(wind_speed_kmh) AS avg_wind_speed_kmh
FROM weather_observations
GROUP BY latitude, longitude, (observed_at AT TIME ZONE 'Asia/Ho_Chi_Minh')::date;
